/// Holes with more boundary edges than this are not filled (an Orca-style small-gap repair only).
pub const MAX_FILL_EDGES: usize = 32;
/// Holes whose vertices deviate from a best-fit plane by more than this fraction of the hole extent are not filled.
const FILL_PLANAR_FRAC: f64 = 0.05;
/// Models whose largest extent is below this (mm) are refused as "tiny scale" (unit mix-up).
pub const MIN_EXTENT_MM: f64 = 1.0;
/// A flat model (smallest extent below this, mm) has no volume.
pub const FLAT_EXTENT_MM: f64 = 0.01;

thread_local! {
    static GUARD_DEPTH: Cell<u32> = Cell::new(0);
    static LAST_PANIC_LOC: RefCell<Option<String>> = RefCell::new(None);
}
static HOOK: Once = Once::new();

fn install_hook() {
    HOOK.call_once(|| {
        let prev = panic::take_hook();
        panic::set_hook(Box::new(move |info| {
            if GUARD_DEPTH.with(|g| g.get()) > 0 {
                let mut loc = info.location().map(|l| format!("{}:{}:{}", l.file(), l.line(), l.column())).unwrap_or_else(|| "unknown location".into());
                // a panic raised inside std (e.g. a sort that detects a non-total order) reports a std path;
                // name the first twobee_fdm frame too, so the owner of the caller is findable.
                if !loc.contains("src/") || loc.starts_with("/rustc/") {
                    let bt = std::backtrace::Backtrace::force_capture().to_string();
                    let mut it = bt.lines();
                    while let Some(l) = it.next() {
                        if l.contains("twobee_fdm::") && !l.contains("pipeline::guard") && !l.contains("install_hook") {
                            let at = it.next().map(|s| s.trim().trim_start_matches("at ").to_string()).unwrap_or_default();
                            loc = format!("{loc} (called from {} {at})", l.trim());
                            break;
                        }
                    }
                }
                LAST_PANIC_LOC.with(|l| *l.borrow_mut() = Some(loc));
            } else {
                prev(info); // not inside the pipeline: behave exactly as before
            }
        }));
    });
}

/// Run `f`; a panic becomes `FdmError::Geometry` carrying the location and message.
pub fn guard<T>(f: impl FnOnce() -> Result<T, FdmError>) -> Result<T, FdmError> {
    install_hook();
    GUARD_DEPTH.with(|g| g.set(g.get() + 1));
    LAST_PANIC_LOC.with(|l| *l.borrow_mut() = None);
    let r = panic::catch_unwind(AssertUnwindSafe(f));
    GUARD_DEPTH.with(|g| g.set(g.get() - 1));
    match r {
        Ok(v) => v,
        Err(p) => {
            let msg = p.downcast_ref::<&str>().map(|s| s.to_string())
                .or_else(|| p.downcast_ref::<String>().cloned())
                .unwrap_or_else(|| "non-string panic payload".into());
            let loc = LAST_PANIC_LOC.with(|l| l.borrow_mut().take()).unwrap_or_else(|| "unknown location".into());
            Err(FdmError::Geometry(format!("internal panic at {loc}: {msg}")))
        }
    }
}

fn describe_defects(r: &crate::mesh::MeshReport, open_loops: usize) -> String {
    format!(
        "mesh defects: {} triangles, {} open edge(s), {} non-manifold edge(s), {} flipped-winding edge(s), {} zero-area triangle(s), {} degenerate triangle(s) dropped at load, volume {:.1} mm3, size {:.2}x{:.2}x{:.2} mm, {} open slice loop(s)",
        r.triangles, r.open_edges, r.nonmanifold_edges, r.flipped_edges, r.zero_area_tris, r.tris_dropped_degenerate, r.volume,
        r.bbox_max[0] - r.bbox_min[0], r.bbox_max[1] - r.bbox_min[1], r.bbox_max[2] - r.bbox_min[2], open_loops)
}

fn tri_key(t: &[u32; 3]) -> [u32; 3] { let mut k = *t; k.sort_unstable(); k }

/// Remove repeated triangles (same three vertices). Same-winding copies collapse to one; a face and its
/// opposite-winding twin cancel (a zero-thickness double wall: keeping one would leave a dangling face).
/// Net = copies(cw) - copies(ccw): |net| copies of the majority winding survive. Returns triangles removed.
fn remove_duplicate_tris(m: &mut Mesh) -> usize {
    let mut groups: BTreeMap<[u32; 3], Vec<usize>> = BTreeMap::new();
    for (i, t) in m.tris.iter().enumerate() { groups.entry(tri_key(t)).or_default().push(i); }
    let mut drop = vec![false; m.tris.len()];
    for idx in groups.values() {
        if idx.len() < 2 { continue; }
        let canon = |t: &[u32; 3]| { let mn = t.iter().position(|&v| v == *t.iter().min().unwrap()).unwrap(); [t[mn], t[(mn + 1) % 3], t[(mn + 2) % 3]] };
        let first = canon(&m.tris[idx[0]]);
        let (same, opp): (Vec<usize>, Vec<usize>) = idx.iter().partition(|&&i| canon(&m.tris[i]) == first);
        // survivors: the majority orientation keeps (|same|-|opp|) copies, but at most 1 (a doubled face is one face)
        let keep_same = if same.len() > opp.len() { 1 } else { 0 };
        let keep_opp = if opp.len() > same.len() { 1 } else { 0 };
        for (list, keep) in [(&same, keep_same), (&opp, keep_opp)] {
            for (k, &i) in list.iter().enumerate() { if k >= keep { drop[i] = true; } }
        }
    }
    let before = m.tris.len();
    let mut i = 0;
    m.tris.retain(|_| { let d = drop[i]; i += 1; !d });
    before - m.tris.len()
}

fn signed_volume6(m: &Mesh, t: &[u32; 3]) -> f64 {
    let (a, b, c) = (m.verts[t[0] as usize], m.verts[t[1] as usize], m.verts[t[2] as usize]);
    a[0] * (b[1] * c[2] - b[2] * c[1]) - a[1] * (b[0] * c[2] - b[2] * c[0]) + a[2] * (b[0] * c[1] - b[1] * c[0])
}

/// Make the winding of every edge-connected patch consistent (flood fill over 2-triangle edges), then flip
/// the whole model when its total signed volume is negative. Returns (triangles flipped, whole model flipped).
fn fix_winding(m: &mut Mesh) -> (usize, bool) {
    let n = m.tris.len();
    let mut edge: BTreeMap<(u32, u32), Vec<(usize, bool)>> = BTreeMap::new();
    for (i, t) in m.tris.iter().enumerate() {
        for k in 0..3 {
            let (a, b) = (t[k], t[(k + 1) % 3]);
            edge.entry((a.min(b), a.max(b))).or_default().push((i, a < b));
        }
    }
    let mut adj: Vec<Vec<(usize, bool, bool)>> = vec![Vec::new(); n]; // (neighbour, my dir, its dir)
    for v in edge.values() {
        if v.len() == 2 {
            adj[v[0].0].push((v[1].0, v[0].1, v[1].1));
            adj[v[1].0].push((v[0].0, v[1].1, v[0].1));
        }
    }
    let mut flip = vec![false; n];
    let mut seen = vec![false; n];
    for s in 0..n {
        if seen[s] { continue; }
        seen[s] = true;
        let mut q = VecDeque::from([s]);
        while let Some(t) = q.pop_front() {
            for &(u, dt, du) in &adj[t] {
                if seen[u] { continue; }
                seen[u] = true;
                // consistent when the two triangles traverse the shared edge in opposite directions
                flip[u] = (dt ^ flip[t]) == (du ^ false);
                q.push_back(u);
            }
        }
    }
    let mut flipped = 0;
    for i in 0..n { if flip[i] { m.tris[i].swap(1, 2); flipped += 1; } }
    let vol: f64 = m.tris.iter().map(|t| signed_volume6(m, t)).sum::<f64>() / 6.0;
    let whole = vol < 0.0;
    if whole { for t in &mut m.tris { t.swap(1, 2); } }
    (flipped, whole)
}

/// Close small simple boundary loops (<= MAX_FILL_EDGES edges, near planar) with a centroid fan (a single
/// triangle for 3-edge loops). Returns (loops filled, triangles added, loops left open).
fn fill_small_holes(m: &mut Mesh) -> (usize, usize, usize) {
    let mut dirs: BTreeMap<(u32, u32), i32> = BTreeMap::new();
    for t in &m.tris { for k in 0..3 { *dirs.entry((t[k], t[(k + 1) % 3])).or_insert(0) += 1; } }
    // boundary half-edges: a->b used, b->a absent. Fill triangles must use b->a.
    let mut next: BTreeMap<u32, Vec<u32>> = BTreeMap::new();
    for (&(a, b), &c) in &dirs {
        if c == 1 && !dirs.contains_key(&(b, a)) { next.entry(a).or_default().push(b); }
    }
    let mut used: BTreeMap<(u32, u32), ()> = BTreeMap::new();
    let (mut filled, mut added, mut left) = (0, 0, 0);
    let starts: Vec<(u32, u32)> = next.iter().flat_map(|(&a, bs)| bs.iter().map(move |&b| (a, b))).collect();
    for (a0, b0) in starts {
        if used.contains_key(&(a0, b0)) { continue; }
        // walk the loop; every vertex must have exactly one outgoing boundary edge (simple loop)
        let mut lp = vec![a0];
        let mut cur = b0;
        used.insert((a0, b0), ());
        let mut ok = true;
        while cur != a0 {
            match next.get(&cur) {
                Some(v) if v.len() == 1 => {
                    used.insert((cur, v[0]), ());
                    lp.push(cur);
                    cur = v[0];
                    if lp.len() > MAX_FILL_EDGES + 1 { ok = false; break; }
                }
                _ => { ok = false; break; }
            }
        }
        if !ok || lp.len() < 3 || lp.len() > MAX_FILL_EDGES { left += 1; continue; }
        // planarity (Newell normal + max distance from the plane through the centroid)
        let pts: Vec<[f64; 3]> = lp.iter().map(|&i| m.verts[i as usize]).collect();
        let c = {
            let mut s = [0.0; 3];
            for p in &pts { for k in 0..3 { s[k] += p[k] / pts.len() as f64; } }
            s
        };
        let mut nrm = [0.0f64; 3];
        for i in 0..pts.len() {
            let (p, q) = (pts[i], pts[(i + 1) % pts.len()]);
            nrm[0] += (p[1] - q[1]) * (p[2] + q[2]);
            nrm[1] += (p[2] - q[2]) * (p[0] + q[0]);
            nrm[2] += (p[0] - q[0]) * (p[1] + q[1]);
        }
        let nl = (nrm[0] * nrm[0] + nrm[1] * nrm[1] + nrm[2] * nrm[2]).sqrt();
        let ext = pts.iter().map(|p| ((p[0] - c[0]).powi(2) + (p[1] - c[1]).powi(2) + (p[2] - c[2]).powi(2)).sqrt()).fold(0.0, f64::max);
        if nl < 1e-12 || ext < 1e-12 { left += 1; continue; }
        let dev = pts.iter().map(|p| (((p[0] - c[0]) * nrm[0] + (p[1] - c[1]) * nrm[1] + (p[2] - c[2]) * nrm[2]) / nl).abs()).fold(0.0, f64::max);
        if dev > FILL_PLANAR_FRAC * ext { left += 1; continue; }
        // lp lists a0, then the walk; boundary edges run lp[i] -> lp[i+1]; the fill uses the reverse direction
        if lp.len() == 3 {
            m.tris.push([lp[1], lp[0], lp[2]]);
            added += 1;
        } else {
            let ci = m.verts.len() as u32;
            m.verts.push(c);
            for i in 0..lp.len() { m.tris.push([lp[(i + 1) % lp.len()], lp[i], ci]); added += 1; }
        }
        filled += 1;
    }
    (filled, added, left)
}

/// Parse + diagnose + (explicitly reported) repair. Refuses flat / tiny / non-finite meshes with the reason.
fn prepare_mesh(stl: &[u8], issues: &mut Vec<String>) -> Result<Mesh, FdmError> {
    let mut mesh = Mesh::from_stl(stl)?;
    let rep = mesh.validate();
    let ext = [rep.bbox_max[0] - rep.bbox_min[0], rep.bbox_max[1] - rep.bbox_min[1], rep.bbox_max[2] - rep.bbox_min[2]];
    if ext.iter().any(|e| !e.is_finite()) { return Err(FdmError::Geometry("mesh has non-finite extent".into())); }
    let (emin, emax) = (ext.iter().cloned().fold(f64::MAX, f64::min), ext.iter().cloned().fold(0.0, f64::max));
    if emin < FLAT_EXTENT_MM {
        return Err(FdmError::Geometry(format!("mesh has no volume: size {:.4}x{:.4}x{:.4} mm is flat (a plane/line/point, {} triangles, {} zero-area, volume {:.3} mm3); nothing to slice",
            ext[0], ext[1], ext[2], rep.triangles, rep.zero_area_tris, rep.volume)));
    }
    if emax < MIN_EXTENT_MM {
        return Err(FdmError::Geometry(format!("mesh is tiny: largest extent {emax:.4} mm (< {MIN_EXTENT_MM} mm), size {:.4}x{:.4}x{:.4} mm; likely a unit mix-up (metres/inches) - scale the model", ext[0], ext[1], ext[2])));
    }
    if rep.is_watertight() && rep.zero_area_tris == 0 && rep.volume > 0.0 { return Ok(mesh); }

    // explicit pre-repair; each step is reported
    let before = describe_defects(&rep, 0);
    let dup = remove_duplicate_tris(&mut mesh);
    if dup > 0 { issues.push(format!("repair: removed {dup} duplicate triangle(s)")); }
    let zero = {
        let before_n = mesh.tris.len();
        let snap = mesh.clone();
        let mut keep = Vec::with_capacity(before_n);
        for (i, t) in snap.tris.iter().enumerate() {
            let a = snap.tri(i);
            let (u, v) = ([a[1][0] - a[0][0], a[1][1] - a[0][1], a[1][2] - a[0][2]], [a[2][0] - a[0][0], a[2][1] - a[0][1], a[2][2] - a[0][2]]);
            let n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
            if n[0] * n[0] + n[1] * n[1] + n[2] * n[2] >= 1e-18 { keep.push(*t); }
        }
        mesh.tris = keep;
        before_n - mesh.tris.len()
    };
    if zero > 0 { issues.push(format!("repair: removed {zero} zero-area triangle(s)")); }
    let mid = mesh.validate();
    if mid.flipped_edges > 0 || mid.volume < 0.0 {
        let (f, whole) = fix_winding(&mut mesh);
        if f > 0 { issues.push(format!("repair: re-oriented {f} triangle(s) to a consistent winding ({} flipped-winding edge(s) before)", mid.flipped_edges)); }
        if whole { issues.push("repair: whole model was inside-out (negative volume); flipped all triangles".into()); }
    }
    let mid = mesh.validate();
    if mid.open_edges > 0 {
        let (filled, added, left) = fill_small_holes(&mut mesh);
        if filled > 0 { issues.push(format!("repair: closed {filled} small hole(s) (<= {MAX_FILL_EDGES} edges, near planar) with {added} triangle(s)")); }
        if left > 0 { issues.push(format!("repair: {left} hole(s) NOT closed (larger than {MAX_FILL_EDGES} edges, non-planar or non-simple)")); }
    }
    let after = mesh.validate();
    if mesh.tris.is_empty() { return Err(FdmError::Geometry(format!("no triangles left after removing degenerate/duplicate ones; {before}"))); }
    if !issues.is_empty() || !after.is_watertight() {
        issues.push(format!("mesh before repair: {}", before));
        if !after.is_watertight() {
            issues.push(format!("mesh after repair still not watertight: {} open edge(s), {} non-manifold edge(s), {} flipped-winding edge(s)", after.open_edges, after.nonmanifold_edges, after.flipped_edges));
        }
    }
    Ok(mesh)
}

/// Refuse (with sizes) a model that does not fit the bed or is placed off it. Never clips.
fn check_bed(mesh: &Mesh, cfg: &Config, place: Placement) -> Result<(), FdmError> {
    let (mn, mx) = mesh.bbox();
    let (w, d, h) = (mx[0] - mn[0], mx[1] - mn[1], mx[2] - mn[2]);
    if let Ok(area) = cfg.points("printable_area") {
        if area.len() >= 3 {
            let (mut lo, mut hi) = ([f64::MAX; 2], [f64::MIN; 2]);
            for p in &area { for k in 0..2 { lo[k] = lo[k].min(p[k]); hi[k] = hi[k].max(p[k]); } }
            let (bw, bd) = (hi[0] - lo[0], hi[1] - lo[1]);
            const TOL: f64 = 0.01;
            if w > bw + TOL || d > bd + TOL {
                return Err(FdmError::Geometry(format!("object footprint {w:.2}x{d:.2} mm (rotation {} deg) is larger than the bed {bw:.1}x{bd:.1} mm (printable_area); scale or split it, nothing was clipped", place.rotate_z_deg)));
            }
            if mn[0] < lo[0] - TOL || mn[1] < lo[1] - TOL || mx[0] > hi[0] + TOL || mx[1] > hi[1] + TOL {
                return Err(FdmError::Geometry(format!("placement puts the object (footprint {w:.2}x{d:.2} mm, x {:.1}..{:.1}, y {:.1}..{:.1}) outside the bed (x {:.1}..{:.1}, y {:.1}..{:.1}); it would be clipped, so the placement centre {:?} is refused",
                    mn[0], mx[0], mn[1], mx[1], lo[0], hi[0], lo[1], hi[1], place.center)));
            }
        }
    }
    if let Ok(ph) = cfg.f64("printable_height") {
        if ph > 0.0 && h > ph + 0.01 {
            return Err(FdmError::Geometry(format!("object height {h:.2} mm is above the printable height {ph:.1} mm (printable_height); nothing was clipped")));
        }
    }
    Ok(())
}

/// Orca refuses a model whose layers have a hole in the middle ("empty layers between z1 and z2"); so do we,
/// Open loops are NOT refused by count: a missing-corner cube has one open loop on each of 128 layers and
/// Orca slices it; the rule that separates it from the bunny (227 loops, 76 empty layers) is the empty-layer gap.
fn check_sliced(sliced: &slice::SliceResult, mesh: &Mesh, issues: &[String]) -> Result<(), FdmError> {
    let layers = &sliced.layers;
    let filled: Vec<usize> = layers.iter().enumerate().filter(|(_, l)| !l.region.is_empty()).map(|(i, _)| i).collect();
    let defects = || format!("{}; {}", describe_defects(&mesh.validate(), sliced.open_loops.len()),
        if issues.is_empty() { "no pre-repair was applied".to_string() } else { issues.join("; ") });
    if filled.is_empty() {
        return Err(FdmError::Geometry(format!("slicing produced no material in any of {} layers (closed contours were not found); {}", layers.len(), defects())));
    }
    let (first, last) = (filled[0], *filled.last().unwrap());
    let gaps: Vec<usize> = (first..=last).filter(|&i| layers[i].region.is_empty()).collect();
    if !gaps.is_empty() {
        return Err(FdmError::Geometry(format!("{} empty layer(s) between z {:.2} and z {:.2} (model has holes in its surface, cannot be printed, same as Orca); {}",
            gaps.len(), layers[gaps[0]].z, layers[*gaps.last().unwrap()].z, defects())));
    }
    Ok(())
}

