//! Pipeline: STL + Orca-resolved settings -> G-code, by wiring the lanes together.
//!
//! mesh -> place -> slice -> walls -> surfaces (shells, bridges) -> sparse infill -> motion/G-code.
//! Settings come from the CONFIG_BLOCK of a reference Orca G-code (`Config::from_gcode`), which is how
//! both slicers get identical inputs for parity runs. Anything a lane refuses (`FdmError::Unsupported`)
//! is returned as an error: the pipeline never approximates a refused feature.
//!
//! Wired behind the Orca keys that select them: supports and raft (`enable_support`, `raft_layers`,
//! `enforce_support_layers`; support layers are merged into the print by z, support first, like
//! `GCode::collect_layers_to_print`), ironing (`ironing_type`), fuzzy skin (`fuzzy_skin`). Refused, never
//! skipped: spiral vase (`spiral_mode`: `effects::spiral` is delivered but the G-code stage has no 3D-move
//! channel), multi-material. Skirt and brim are generated by the G-code stage from the layer slices; no lane
//! may emit Skirt/Brim paths (the pipeline reports one if it ever sees it, because the G-code stage would then
//! print only those and skip its own). Per-layer work runs in parallel with results stored by layer index.

