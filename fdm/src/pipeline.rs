    #[test]
    fn two_objects_two_filaments_join_into_tool_changes_tower_and_per_object_blocks() {
        let Some(reff) = fixture() else { eprintln!("PENDING: no multi-material fixture (FDM_MM_FIX / ~/build/fdm-corpus/mm/orca.gcode)"); return; };
        let r = slice_job(&[obj("a.stl", 0, 127.25, 128.0), obj("b.stl", 1, 149.25, 128.0)], &reff, &JobOptions::default()).expect("2x2 job");
        let g = &r.gcode;
        let layers = r.layers;
        assert_eq!(layers, 100);
        // both filaments are selected, and the file starts on filament 0 (a) like Orca's
        let tcs: Vec<usize> = g.lines().filter_map(|l| l.strip_prefix("M620 S").and_then(|r| r.split(|c: char| !c.is_ascii_digit()).next()).and_then(|d| d.parse().ok())).collect();
        assert!(tcs.contains(&0) && tcs.contains(&1), "{tcs:?}");
        // one tool change per layer (every layer has both objects) beyond the initial load: 102 = Orca's count on this plate
        assert_eq!(tcs.len(), 102, "tool-change macro count");
        // the prime tower is printed on every layer
        let tower_layers = g.split("; CHANGE_LAYER").skip(1).filter(|l| l.contains("; FEATURE: Prime tower")).count();
        assert_eq!(tower_layers, layers, "layers carrying a tower piece");
        // object attribution: after T1 the object printed is b, after T0 it is a (the tool change moves the object block)
        let (mut cur, mut checked) = (usize::MAX, 0);
        for l in g.lines() {
            if let Some(t) = l.strip_prefix("T").and_then(|r| r.split_whitespace().next()).and_then(|d| d.parse::<usize>().ok()) { if t < 2 { cur = t; } }
            if let Some(n) = l.strip_prefix("; printing object ") {
                if cur == usize::MAX { continue; }
                let want = if cur == 0 { "a.stl" } else { "b.stl" };
                assert!(n.starts_with(want), "after T{cur} object block is {n:?}");
                checked += 1;
            }
        }
        assert!(checked >= layers, "only {checked} object blocks checked");
        // negative control: the same plate on ONE filament has no tool change and no tower
        let one = slice_job(&[obj("a.stl", 0, 127.25, 128.0), obj("b.stl", 0, 149.25, 128.0)], &reff, &JobOptions::default()).expect("1-filament job");
        assert!(one.gcode.matches("; FEATURE: Prime tower").count() == 0, "tower on a one-filament plate");
        assert!(!one.gcode.lines().any(|l| l.starts_with("T1")), "T1 on a one-filament plate");
    }

