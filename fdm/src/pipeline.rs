pub struct JobOutput {
    pub gcode: String,
    pub layers: usize,
    pub issues: Vec<String>,
    pub open_loops: usize,
    pub objects: Vec<ObjectStats>,
    pub plans: Vec<LayerPlan>,
}

/// Several STLs + the settings of a reference Orca G-code -> one G-code (by-layer print sequence).
pub fn slice_job(objects: &[JobObject], reference_gcode: &str, opts: &JobOptions) -> Result<JobOutput, FdmError> {
    guard(|| {
        let cfg = Config::from_gcode(reference_gcode)?;
        slice_job_with_config(objects, &cfg, opts)
    })
}

pub fn slice_job_with_config(objects: &[JobObject], cfg: &Config, _opts: &JobOptions) -> Result<JobOutput, FdmError> {
    guard(|| slice_job_inner(objects, cfg))
}

/// 🔴 Pinned objects that overlap (bughunt 2026-11-15). A manual placement was sliced with no check, so two objects
/// sharing plate area each laid their own walls and infill over the same spot: double extrusion there, and the nozzle
/// ploughing into the first object's plastic on every layer. The browser's layout check catches it before a job is
/// sent; the bridge and `fdmslice --multi` take placements from anywhere. Compared on the real slice at each shared Z,
/// not on bounding boxes, so outline-nested parts that only interlock are accepted. Arranged jobs are not checked:
/// the arranger places them apart.
fn refuse_overlap(objects: &[JobObject], order: &[usize], plans_per: &[ObjectPlan]) -> Result<(), FdmError> {
    const EPS_Z: f64 = 1e-4;
    const MIN_AREA: f64 = 0.01; // mm^2: touching outlines intersect in a line, not an area
    let boxes: Vec<Option<[f64; 4]>> = plans_per.iter().map(|o| {
        o.slices.iter().filter_map(geom::bbox).reduce(|a, b| [a[0].min(b[0]), a[1].min(b[1]), a[2].max(b[2]), a[3].max(b[3])])
    }).collect();
    for a in 0..plans_per.len() {
        for b in a + 1..plans_per.len() {
            let (Some(ba), Some(bb)) = (boxes[a], boxes[b]) else { continue };
            if ba[2] <= bb[0] || bb[2] <= ba[0] || ba[3] <= bb[1] || bb[3] <= ba[1] { continue; }
            let (pa, pb) = (&plans_per[a], &plans_per[b]);
            let mut j = 0;
            for (i, la) in pa.plans.iter().enumerate() {
                while j < pb.plans.len() && pb.plans[j].z < la.z - EPS_Z { j += 1; }
                if j >= pb.plans.len() { break; }
                if (pb.plans[j].z - la.z).abs() >= EPS_Z || pa.slices[i].is_empty() || pb.slices[j].is_empty() { continue; }
                let shared = geom::area(&geom::intersect(&pa.slices[i], &pb.slices[j]));
                if shared > MIN_AREA {
                    return Err(FdmError::Geometry(format!("{} and {} overlap on the plate ({shared:.2} mm2 shared at z {:.2}); move them apart",
                        objects[order[a]].name, objects[order[b]].name, la.z)));
                }
            }
        }
    }
    Ok(())
}

fn slice_job_inner(objects: &[JobObject], cfg: &Config) -> Result<JobOutput, FdmError> {
    use crate::arrange;
    if objects.is_empty() { return Err(FdmError::Parse("job has no objects".into())); }
    if cfg.raw("print_sequence").map_or(false, |v| v.trim() == "by object") {
        return Err(FdmError::Unsupported("print_sequence = by object with several objects".into()));
    }
    let nfil_cfg = cfg.raw("filament_type").map_or(1, |v| v.split(';').count().max(1));
    if let Some(o) = objects.iter().find(|o| o.filament_index >= nfil_cfg) {
        return Err(FdmError::Unsupported(format!("{}: filament slot {} but the settings define {} filament(s)", o.name, o.filament_index, nfil_cfg)));
    }
    let multi_fil = objects.iter().any(|o| o.filament_index != 0);
    refuse_unwired(cfg)?;
    refuse_bad_values(cfg)?;
    check_object_overrides(cfg, objects)?;
    let mut issues: Vec<String> = Vec::new();
    let mut meshes: Vec<Mesh> = Vec::new();
    for o in objects { 
        let mut sub = Vec::new();
        meshes.push(prepare_mesh(&o.stl, &mut sub).map_err(|e| FdmError::Geometry(format!("{}: {e}", o.name)))?);
        issues.extend(sub.into_iter().map(|m| format!("{}: {m}", o.name)));
    }
    let n = objects.len();
    let manual = objects.iter().filter(|o| o.placement.is_some()).count();
    if manual != 0 && manual != n { return Err(FdmError::Unsupported("mixed manual and automatic placement: give every object a placement, or none".into())); }
    let mut rots = vec![0.0f64; n];
    let mut shifts = vec![[0.0f64; 2]; n]; // instance shift Orca orders the print by
    if manual == 0 {
        let items: Vec<arrange::SceneItem> = objects.iter().zip(&meshes).map(|(o, m)| arrange::SceneItem { name: o.name.clone(), mesh: m, filament: o.filament_index }).collect();
        let placed = arrange::arrange_scene(&items, cfg).map_err(FdmError::Geometry)?;
        for p in &placed {
            let (mn, mx) = meshes[p.index].bbox();
            let c0 = [(mn[0] + mx[0]) / 2.0, (mn[1] + mx[1]) / 2.0];
            shifts[p.index] = [p.origin[0] + c0[0], p.origin[1] + c0[1]];
            rots[p.index] = p.rotation.to_degrees();
            arrange::place_mesh(&mut meshes[p.index], p);
        }
    } else {
        for (i, o) in objects.iter().enumerate() {
            let pl = o.placement.unwrap();
            rotate_z(&mut meshes[i], pl.rotate_z_deg);
            meshes[i].place_on_bed(pl.center[0], pl.center[1]);
            rots[i] = pl.rotate_z_deg;
            shifts[i] = pl.center;
        }
    }
    let order = arrange::print_order(&shifts);
    // per-object planning (the heavy part); objects are independent
    let mut plans_per: Vec<ObjectPlan> = Vec::new();
    let mut applied: Vec<Vec<(String, String)>> = vec![Vec::new(); n];
    for &i in &order {
        let pl = Placement { rotate_z_deg: rots[i], center: shifts[i] };
        let mesh = meshes[i].clone();
        check_bed(&mesh, cfg, pl)?;
        // The object's own config: the plate's plus its overrides. Its reads are merged back into the plate's tracker.
        let own;
        let ocfg: &Config = if objects[i].overrides.is_empty() { cfg } else {
            let mut c = Config::from_map(cfg.raw_map().clone());
            for (k, v) in &objects[i].overrides { c.set(k, v); }
            own = c;
            &own
        };
        applied[i] = objects[i].overrides.iter().map(|(k, _)| (k.clone(), ocfg.raw_map().get(k).cloned().unwrap_or_default())).collect();
        let planned = plan_object(mesh, ocfg, pl, &mut issues);
        if !std::ptr::eq(ocfg, cfg) { cfg.absorb_reads(ocfg); }
        plans_per.push(planned.map_err(|e| match e { FdmError::Geometry(m) => FdmError::Geometry(format!("{}: {m}", objects[i].name)), FdmError::Unsupported(m) => FdmError::Unsupported(format!("{}: {m}", objects[i].name)), o => o })?);
    }
    if manual != 0 { refuse_overlap(objects, &order, &plans_per)?; }
    // merge by z (support layers keep their own z); objects in print order inside a layer
    const EPS: f64 = 1e-4;
    let mut zs: Vec<f64> = plans_per.iter().flat_map(|o| o.plans.iter().map(|p| p.z)).collect();
    zs.sort_by(|a, b| a.partial_cmp(b).unwrap());
    zs.dedup_by(|a, b| (*a - *b).abs() < EPS);
    let mut plans: Vec<LayerPlan> = Vec::with_capacity(zs.len());
    let mut slices: Vec<Polys> = Vec::with_capacity(zs.len());
    // side tables for the multi-material G-code stage: filament of every merged path (objects reach the stage through GcodeOptions::objects)
    let mut path_fil: Vec<Vec<usize>> = Vec::with_capacity(zs.len());
    let mut cursor = vec![0usize; plans_per.len()];
    for &z in &zs {
        let mut lp = LayerPlan { z, h: 0.0, paths: Vec::new() };
        let mut sl: Polys = Vec::new();
        let mut pf: Vec<usize> = Vec::new();
        for (k, o) in plans_per.iter().enumerate() {
            let c = cursor[k];
            if c < o.plans.len() && (o.plans[c].z - z).abs() < EPS {
                if lp.h == 0.0 { lp.h = o.plans[c].h; }
                let n_new = o.plans[c].paths.len();
                pf.extend(std::iter::repeat(objects[order[k]].filament_index).take(n_new));
                lp.paths.extend(o.plans[c].paths.iter().cloned());
                sl.extend(o.slices[c].iter().cloned());
                cursor[k] += 1;
            }
        }
        plans.push(lp);
        slices.push(sl);
        path_fil.push(pf);
    }
    // gcode stage
    let settings = Settings::from_config(cfg);
    let mut gopts = GcodeOptions::default();
    gopts.slices = Some(slices);
    let mut tris = Vec::new();
    for o in &plans_per { for i in 0..o.mesh.tris.len() { tris.push(o.mesh.tri(i)); } }
    gopts.seam_mesh = Some(gcode::SeamMesh { tris, rot_deg: 0.0, center: [0.0, 0.0] });
    gopts.object_name = objects[order[0]].name.clone();
    if n > 1 {
        gopts.seam_objects = plans_per.iter().map(|o| (0..o.mesh.tris.len()).map(|i| o.mesh.tri(i)).collect()).collect();
    }
    if n > 1 {
        gopts.objects = order.iter().enumerate().map(|(pos, &i)| {
            let pts: Vec<arrange::Pt> = plans_per[pos].mesh.verts.iter().map(|v| [(v[0] * 1e6).round() as i64, (v[1] * 1e6).round() as i64]).collect();
            let hull = arrange::convex_hull(&pts).iter().map(|p| [p[0] as f64 / 1e6, p[1] as f64 / 1e6]).collect();
            gcode::GcodeObject { name: objects[i].name.clone(), id: i as u64, label_id: 45 + 11 * i as u32, footprint: hull, filament: objects[i].filament_index }
        }).collect();
    }
    if multi_fil || nfil_cfg > 1 {
        // Several objects on several filaments (or one non-default filament): the G-code stage places the tool changes,
        // the prime tower and the per-filament temperature / retraction / cooling.
        gopts.multi = Some(gcode::MultiMaterial {
            path_filament: path_fil,
            path_object: None,
            objects: Vec::new(),
            tower_pos: None,
            filament_count: Some(nfil_cfg),
        });
    }
    let mut t0 = std::time::Instant::now();
    let mut out = gcode::generate(&plans, &settings, &gopts)?;
    absorb_settings_reads(cfg, &settings);
    stage(&mut t0, "gcode");
    // The CONFIG_BLOCK states the plate-wide values; an object planned with its own says so in the header, so the file
    // does not claim one wall count for a part printed with another.
    let notes: String = order.iter().filter(|&&i| !applied[i].is_empty()).map(|&i| format!("; object {i} ({}) planned with its own: {}\n", objects[i].name,
        applied[i].iter().map(|(k, v)| format!("{k} = {v}")).collect::<Vec<_>>().join(", "))).collect();
    if !notes.is_empty() {
        if let Some(at) = out.gcode.find("; HEADER_BLOCK_END\n") { out.gcode.insert_str(at, &notes); }
        else { return Err(FdmError::Geometry("per-object settings: no HEADER_BLOCK_END to state them in".into())); }
    }
    issues.extend(out.issues);
    let stats = order.iter().enumerate().map(|(pos, &i)| {
        let (mn, mx) = plans_per[pos].mesh.bbox();
        ObjectStats { name: objects[i].name.clone(), input_index: i, print_position: pos, rotate_z_deg: rots[i], center: [(mn[0] + mx[0]) / 2.0, (mn[1] + mx[1]) / 2.0],
            bbox: [mn[0], mn[1], mx[0], mx[1]], layers: plans_per[pos].plans.len(), height: mx[2] - mn[2], extrusion_paths: plans_per[pos].plans.iter().map(|p| p.paths.len()).sum(),
            overrides: applied[i].clone() }
    }).collect();
    let open_loops = plans_per.iter().map(|o| o.open_loops).sum();
    Ok(JobOutput { gcode: out.gcode, layers: plans.len(), issues, open_loops, objects: stats, plans })
}

