/// Where the object goes on the bed, and how it is turned first (Orca's arrange may rotate the object;
/// the parity tool finds the rotation that reproduces Orca's footprint and passes it in).
#[derive(Clone, Copy, Debug)]
pub struct Placement {
    /// Rotation about Z in degrees, applied about the mesh XY centre before placement.
    pub rotate_z_deg: f64,
    /// Bed point the object's XY bounding-box centre is moved to.
    pub center: [f64; 2],
}

impl Default for Placement {
    fn default() -> Self { Placement { rotate_z_deg: 0.0, center: [128.0, 128.0] } }
}

/// Everything the pipeline produced, so callers (parity, quality tools) can look inside.
pub struct PipelineOutput {
    pub gcode: String,
    pub layers: usize,
    pub plans: Vec<LayerPlan>,
    pub issues: Vec<String>,
    pub open_loops: usize,
}

/// Settings that select a feature the pipeline cannot run: refuse with the reason (never skip).
/// `FDM_TIMING=1`: wall time per pipeline stage on stderr. Read once; prints nothing otherwise and never changes output.
pub(crate) fn stage(t0: &mut std::time::Instant, name: &str) {
    static ON: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    if *ON.get_or_init(|| std::env::var_os("FDM_TIMING").is_some()) { eprintln!("fdm-timing {name:<12} {:>8.1} ms", t0.elapsed().as_secs_f64() * 1e3); }
    *t0 = std::time::Instant::now();
}

fn refuse_unwired(cfg: &Config) -> Result<(), FdmError> {
    let on = |k: &str| cfg.raw(k).map_or(false, |v| matches!(v.trim(), "1" | "true"));
    // XY contour / hole compensation are not implemented. They were IGNORED until 2026-11-12 (G-code identical with and
    // without); a size change the user asked for that silently does not happen is a wrong part, so a non-zero value
    // is refused instead.
    for k in ["xy_contour_compensation", "xy_hole_compensation"] {
        if cfg.raw(k).and_then(|v| v.trim().parse::<f64>().ok()).map_or(false, |v| v.abs() > 1e-9) {
            return Err(FdmError::Unsupported(format!("{k} is not implemented in 2bee.fdm; set it to 0")));
        }
    }
    // 🔴 Shrinkage compensation (bughunt 2026-11-15). Orca scales the part by 100/shrink in XY and Z
    // (PrintApply.cpp:1270); this engine read neither key, so a 99.5% filament printed 0.5% small with exit 0. Same
    // failure as the XY compensation above: the size the user asked for silently does not happen. Every BBL profile
    // ships 100%; anything else is refused. `nil` is Orca's "not overridden" marker.
    for k in ["filament_shrink", "filament_shrinkage_compensation_z"] {
        let Some(raw) = cfg.raw(k) else { continue };
        let off = raw.split(',').map(|e| e.trim()).filter(|e| *e != "nil" && !e.is_empty())
            .any(|e| e.trim_end_matches('%').parse::<f64>().map_or(true, |v| (v - 100.0).abs() > 1e-9));
        if off {
            return Err(FdmError::Unsupported(format!("{k} = {raw} is not implemented in 2bee.fdm \
                (the part would print unscaled); set it to 100%")));
        }
    }
    // 🔴 Absolute E (2026-11-14). `use_relative_e_distances = 0` wrote `M82` and then the per-move DELTAS, with no
    // `G92 E0`: the firmware reads each small delta as an absolute position, so the filament reverses on nearly
    // every move. The writer has no absolute-E output, so the setting is refused rather than half-honoured.
    if cfg.raw("use_relative_e_distances").map_or(false, |v| matches!(v.trim(), "0" | "false")) {
        return Err(FdmError::Unsupported("use_relative_e_distances = 0 (absolute E) is not implemented in 2bee.fdm: \
            the writer emits relative E only; set it to 1".into()));
    }
    // 🔴 Spiral vase with the settings the GUI would force left unforced (2026-11-14). The CLI does not force them
    // and the layers that violate them are not spiralised; measured: a 2-wall box spiralised ONLY its one-wall top
    // layer, ramping flow up from 0 % along the top edge. Refused, naming the keys, as the violations list says.
    if on("spiral_mode") {
        let n = |k: &str, d: f64| num_of(cfg, k, d);
        let v = crate::effects::spiral::spiral_config_violations(
            n("wall_loops", 1.0) as u32, n("top_shell_layers", 0.0) as u32, n("sparse_infill_density", 0.0),
            on("enable_support"), on("detect_thin_wall"), on("overhang_reverse"));
        if !v.is_empty() {
            return Err(FdmError::Unsupported(format!("spiral_mode needs wall_loops 1, top_shell_layers 0, \
                sparse_infill_density 0, no support, no thin-wall detection and no overhang_reverse; violated: {}", v.join(", "))));
        }
    }
    Ok(())
}

/// 🔴 Values the G-code stage cannot be trusted with (bughunt 2026-11-15). `Settings::num` reads an unparseable
/// number as 0 with no issue, while the slicing stage reads strictly — so `filament_diameter = abc` (or `0`) wrote
/// `E92233720368547.75807`, `filament_flow_ratio = abc` printed with `E0` throughout, `retraction_length = abc` dropped
/// every retraction, `z_hop = abc` dragged the nozzle across the part, `textured_plate_temp = abc` sent `M140 S0` at
/// layer 2 and `nozzle_temperature_initial_layer = abc` printed layer 1 at 0 degC — all with exit 0. Every numeric
/// option is now refused unless each element parses as a finite number (`nil` is Orca's "not overridden" marker), and
/// the few values whose ZERO or sign is itself the hazard are bounded. Physical failures guarded: a runaway or dead
/// extruder, a nozzle dragged through the print, a cold first layer, a bed that switches off mid-print.
fn refuse_bad_values(cfg: &Config) -> Result<(), FdmError> {
    use crate::motion::settings::{opt_kind, OptKind};
    let s = Settings::from_config(cfg);
    let mut bad = Vec::new();
    for (k, raw) in s.iter() {
        if !matches!(opt_kind(k).0, OptKind::Float | OptKind::Int | OptKind::Percent | OptKind::FloatOrPercent) { continue; }
        let ok = s.elements(k).iter().all(|e| {
            let t = e.trim();
            t == "nil" || t.trim_end_matches('%').parse::<f64>().map_or(false, |v| v.is_finite())
        });
        if !ok { bad.push(format!("{k} = {raw}")); }
    }
    if !bad.is_empty() {
        return Err(FdmError::Parse(format!("not a number where one is required (would be read as 0): {}", bad.join("; "))));
    }
    let all = |k: &str| s.elements(k).iter().filter(|e| e.trim() != "nil").filter_map(|e| e.trim().trim_end_matches('%').parse::<f64>().ok()).collect::<Vec<_>>();
    for k in ["filament_diameter", "filament_flow_ratio", "nozzle_diameter"] {
        if s.has(k) && all(k).iter().any(|v| *v <= 0.0) {
            return Err(FdmError::Parse(format!("{k} = {} must be above 0", s.raw(k).unwrap_or(""))));
        }
    }
    for k in ["retraction_length", "z_hop"] {
        if all(k).iter().any(|v| *v < 0.0) {
            return Err(FdmError::Parse(format!("{k} = {} must not be negative", s.raw(k).unwrap_or(""))));
        }
    }
    // Orca refuses a layer taller than the printer allows; this engine sliced it at 2.4x the extrusion per mm.
    let lh = s.num("layer_height");
    let max_lh = all("max_layer_height").into_iter().filter(|v| *v > 0.0).fold(f64::INFINITY, f64::min);
    let nozzle = all("nozzle_diameter").into_iter().fold(f64::INFINITY, f64::min);
    if s.has("layer_height") && (lh > max_lh + 1e-9 || lh > nozzle + 1e-9) {
        return Err(FdmError::Parse(format!(
            "layer_height {lh} is above what this printer allows (max_layer_height {max_lh}, nozzle {nozzle})")));
    }
    Ok(())
}

/// The G-code stage reads a copy of the config (`Settings`); without this every key only it reads stayed in
/// `Config::unread_keys`, and fdmslice's `unreadKeys` counted read keys as ignored (bughunt 2026-11-15).
/// ⚠ Per-filament copies (`Settings::for_filament`, multi-material) keep their own reads; those are not merged.
fn absorb_settings_reads(cfg: &Config, s: &Settings) {
    let keys = s.read_keys();
    cfg.mark_read(&keys.iter().map(String::as_str).collect::<Vec<_>>());
}

fn num_of(cfg: &Config, k: &str, d: f64) -> f64 {
    cfg.raw(k).and_then(|v| v.split(',').next().map(|s| s.trim().trim_end_matches('%').to_string())).and_then(|s| s.parse::<f64>().ok()).unwrap_or(d)
}

/// Ironing settings (`None` for "no ironing").
fn ironing_config(cfg: &Config) -> Result<Option<IroningConfig>, FdmError> {
    let kind_key = match cfg.raw("ironing_type") { Some(v) => v.trim().to_string(), None => return Ok(None) };
    let kind = IroningType::from_key(&kind_key).ok_or_else(|| FdmError::Parse(format!("ironing_type = {kind_key:?} is not a known value")))?;
    if kind == IroningType::NoIroning { return Ok(None); }
    if cfg.raw("solid_infill_rotate_template").map_or(false, |v| !v.trim().is_empty()) {
        return Err(FdmError::Unsupported("ironing with solid_infill_rotate_template (calculate_infill_rotation_angle template) is not ported".into()));
    }
    let pat_key = cfg.raw("ironing_pattern").map(|v| v.trim().to_string()).unwrap_or_else(|| "rectilinear".into());
    let pattern = SurfacePattern::from_key(&pat_key).ok_or_else(|| FdmError::Parse(format!("ironing_pattern = {pat_key:?} is not a known value")))?;
    let d = IroningConfig::default();
    Ok(Some(IroningConfig {
        kind, speed: num_of(cfg, "ironing_speed", d.speed), flow_percent: num_of(cfg, "ironing_flow", d.flow_percent),
        spacing: num_of(cfg, "ironing_spacing", d.spacing), inset: num_of(cfg, "ironing_inset", d.inset),
        angle_deg: num_of(cfg, "ironing_angle", 0.0), angle_fixed: cfg.raw("ironing_angle_fixed").map_or(false, |v| v.trim() == "1"),
        pattern, nozzle_diameter: num_of(cfg, "nozzle_diameter", d.nozzle_diameter), layer_height: num_of(cfg, "layer_height", d.layer_height),
        top_shell_layers: num_of(cfg, "top_shell_layers", 5.0) as u32, bottom_shell_layers: num_of(cfg, "bottom_shell_layers", 3.0) as u32,
        spiral_mode: false, sparse_infill_density: num_of(cfg, "sparse_infill_density", 15.0),
    }))
}

/// Fuzzy skin settings (`None` when disabled).
fn fuzzy_config(cfg: &Config) -> Result<Option<FuzzyConfig>, FdmError> {
    let key = match cfg.raw("fuzzy_skin") { Some(v) => v.trim().to_string(), None => return Ok(None) };
    let kind = FuzzySkinType::from_key(&key).ok_or_else(|| FdmError::Parse(format!("fuzzy_skin = {key:?} is not a known value")))?;
    if matches!(kind, FuzzySkinType::None | FuzzySkinType::Disabled) { return Ok(None); }
    let get = |k: &str| cfg.raw(k).map(|v| v.trim().to_string());
    let mut c = FuzzyConfig::default();
    c.kind = kind;
    c.thickness = num_of(cfg, "fuzzy_skin_thickness", c.thickness);
    c.point_distance = num_of(cfg, "fuzzy_skin_point_distance", c.point_distance);
    c.first_layer = get("fuzzy_skin_first_layer").map_or(false, |v| v == "1");
    if let Some(v) = get("fuzzy_skin_noise_type") { c.noise_type = NoiseType::from_key(&v).ok_or_else(|| FdmError::Parse(format!("fuzzy_skin_noise_type = {v:?}")))?; }
    c.noise_scale = num_of(cfg, "fuzzy_skin_scale", c.noise_scale);
    c.noise_octaves = num_of(cfg, "fuzzy_skin_octaves", c.noise_octaves as f64) as i32;
    c.noise_persistence = num_of(cfg, "fuzzy_skin_persistence", c.noise_persistence);
    if let Some(v) = get("fuzzy_skin_mode") { c.mode = FuzzyMode::from_key(&v).ok_or_else(|| FdmError::Parse(format!("fuzzy_skin_mode = {v:?}")))?; }
    c.ripples_per_layer = num_of(cfg, "fuzzy_skin_ripples_per_layer", c.ripples_per_layer);
    c.ripple_offset = num_of(cfg, "fuzzy_skin_ripple_offset", c.ripple_offset);
    c.layers_between_ripple_offset = num_of(cfg, "fuzzy_skin_layers_between_ripple_offset", c.layers_between_ripple_offset as f64) as i32;
    Ok(Some(c))
}

/// Brim footprint used to trim first-layer supports (`SupportMaterial.cpp`, "calculate the area covered by the brim").
fn brim_footprint(cfg: &Config, first_layer: &Polys) -> Option<Polys> {
    let t = cfg.raw("brim_type").map(|v| v.trim().to_string()).unwrap_or_else(|| "no_brim".into());
    if t == "no_brim" || num_of(cfg, "brim_width", 0.0) <= 0.0 { return None; }
    let gap = num_of(cfg, "brim_object_gap", 0.0);
    let outer = matches!(t.as_str(), "outer_only" | "outer_and_inner" | "auto_brim");
    let inner = matches!(t.as_str(), "inner_only" | "outer_and_inner");
    let mut out: Polys = Vec::new();
    for p in first_layer {
        if outer && inner { out.extend(geom::offset_round(&vec![p.clone()], gap, 0.1)); continue; }
        if outer { out.extend(geom::offset_round(&vec![Poly { contour: p.contour.clone(), holes: vec![] }], gap, 0.1)); } else { out.push(Poly { contour: p.contour.clone(), holes: vec![] }); }
        if inner {
            let holes: Polys = p.holes.iter().map(|h| { let mut c = h.clone(); c.reverse(); Poly { contour: c, holes: vec![] } }).collect();
            out.extend(geom::offset_round(&holes, -gap, 0.1));
        }
    }
    Some(geom::union_all(&[&out]))
}

/// Merge the support layers of `sp` into the object `plans` by print z (EPSILON 1e-4): a support layer within EPSILON of an
/// object layer shares its LayerPlan (support paths first), the others become LayerPlans of their own. Object layer z is
/// shifted by `sp.object_z_shift` (raft); the first object layer takes `first_object_layer_height` when a raft exists.
fn interleave(plans: Vec<LayerPlan>, layers: &[Layer], sp: &SupportPlan) -> (Vec<LayerPlan>, Vec<Polys>) {
    const EPS: f64 = 1e-4;
    let shift = sp.object_z_shift;
    let mut out_plans: Vec<LayerPlan> = Vec::with_capacity(plans.len() + sp.layers.len());
    let mut out_slices: Vec<Polys> = Vec::with_capacity(plans.len() + sp.layers.len());
    let mut si = 0usize;
    for (i, mut p) in plans.into_iter().enumerate() {
        let oz = p.z + shift;
        // support layers strictly below this object layer print first, each on its own layer
        while si < sp.layers.len() && sp.layers[si].z < oz - EPS {
            let sl = &sp.layers[si];
            out_plans.push(LayerPlan { z: sl.z, h: sl.h, paths: sl.paths.clone() });
            out_slices.push(Vec::new());
            si += 1;
        }
        let mut paths: Vec<ExtPath> = Vec::new();
        if si < sp.layers.len() && (sp.layers[si].z - oz).abs() <= EPS { paths.extend(sp.layers[si].paths.iter().cloned()); si += 1; }
        paths.extend(std::mem::take(&mut p.paths));
        // the raft lifts the first object layer to its own height
        let h = if i == 0 { sp.first_object_layer_height.unwrap_or(p.h) } else { p.h };
        out_plans.push(LayerPlan { z: oz, h, paths });
        out_slices.push(layers[i].region.clone());
    }
    while si < sp.layers.len() {
        let sl = &sp.layers[si];
        out_plans.push(LayerPlan { z: sl.z, h: sl.h, paths: sl.paths.clone() });
        out_slices.push(Vec::new());
        si += 1;
    }
    (out_plans, out_slices)
}

/// Generate supports / raft and interleave them with the object layers by print z (EPSILON 1e-4, like
/// `GCode::collect_layers_to_print`): a support layer within EPSILON of an object layer shares its LayerPlan (support
/// paths FIRST: Orca extrudes the support layer before the object layer), others become their own LayerPlan.
/// Returns the plans and, per plan, the object slice used for island grouping (empty for support-only layers).
fn merge_supports(cfg: &Config, slice_cfg: &Config, mesh: &Mesh, layers: &[Layer], plans: Vec<LayerPlan>, origin: [f64; 2], issues: &mut Vec<String>) -> Result<(Vec<LayerPlan>, Vec<Polys>), FdmError> {
    let on = |k: &str| cfg.raw(k).map_or(false, |v| matches!(v.trim(), "1" | "true"));
    let int = |k: &str| num_of(cfg, k, 0.0) as i64;
    if !(on("enable_support") || int("enforce_support_layers") > 0 || int("raft_layers") > 0) {
        return Ok((plans, layers.iter().map(|l| l.region.clone()).collect()));
    }
    let scfg = SupportConfig::from_kv(cfg.raw_map())?;
    let brim = brim_footprint(cfg, &layers[0].region);
    // The support generator gets the layer stack sliced WITHOUT the slice_closing_radius offset round trip: measured on a
    // round part (mushroom), the closed slices leave sliver polygons that make it insert spurious intermediate layers
    // (86 -> 71..76 layers vs Orca's 86), while the unclosed slices reproduce Orca's layer stack exactly. Approximation:
    // gaps up to 2*slice_closing_radius (0.098 mm) in the mesh are not bridged for the support computation only.
    let (_, mx) = mesh.bbox();
    let specs = slice::stack_from_config(slice_cfg, mx[2])?;
    let mut so = slice::SliceOptions::from_config(slice_cfg);
    let had_closing = so.closing_radius > 0.0;
    so.closing_radius = 0.0;
    let support_layers_in = slice::slice_mesh(mesh, &specs, so).layers;
    if had_closing { issues.push("supports: generated from slices without slice_closing_radius (the closing round trip leaves slivers the support generator mishandles)".into()); }
    let sp: SupportPlan = supports::generate(&SupportInput { cfg: &scfg, layers: &support_layers_in, origin, enforcers: &[], blockers: &[], brim: brim.as_ref() })?;
    for n in &sp.notes { issues.push(format!("supports: {n}")); }
    let shift = sp.object_z_shift;
    let (out_plans, out_slices) = interleave(plans, layers, &sp);
    if shift != 0.0 { issues.push(format!("raft: object layers shifted up by {shift:.3} mm")); }
    Ok((out_plans, out_slices))
}

fn rotate_z(mesh: &mut Mesh, deg: f64) {
    if deg == 0.0 || mesh.verts.is_empty() { return; }
    let (mut lo, mut hi) = ([f64::MAX; 2], [f64::MIN; 2]);
    for v in &mesh.verts { for a in 0..2 { lo[a] = lo[a].min(v[a]); hi[a] = hi[a].max(v[a]); } }
    let (cx, cy) = ((lo[0] + hi[0]) / 2.0, (lo[1] + hi[1]) / 2.0);
    let (s, c) = deg.to_radians().sin_cos();
    for v in &mut mesh.verts {
        let (x, y) = (v[0] - cx, v[1] - cy);
        v[0] = cx + x * c - y * s;
        v[1] = cy + x * s + y * c;
    }
}

fn to_points(paths: &[ExtPath]) -> Vec<Vec<[f64; 2]>> {
    paths.iter().map(|p| p.pts.iter().map(|q| [q.x, q.y]).collect()).collect()
}

/// STL bytes + a reference G-code (for its CONFIG_BLOCK) -> our G-code.
pub fn slice_gcode(stl: &[u8], reference_gcode: &str, place: Placement) -> Result<PipelineOutput, FdmError> {
    guard(|| {
        let cfg = Config::from_gcode(reference_gcode)?;
        slice_inner(stl, &cfg, place)
    })
}

/// The whole pipeline behind a panic guard: any panic in any lane becomes `FdmError::Geometry("internal
/// panic at <file:line>: <message>")`, so a caller is never crashed by a model.
pub fn slice_with_config(stl: &[u8], cfg: &Config, place: Placement) -> Result<PipelineOutput, FdmError> {
    guard(|| slice_inner(stl, cfg, place))
}

/// One object's finished layers: plans (supports merged), the slice used for island grouping per plan.
pub struct ObjectPlan {
    pub mesh: Mesh,
    pub plans: Vec<LayerPlan>,
    pub slices: Vec<Polys>,
    pub open_loops: usize,
    pub centre: [f64; 2],
}

/// Everything per object up to the finished layer plans (slice, walls, surfaces, infill, ironing, supports). `mesh` is already placed.
fn plan_object(mesh: Mesh, cfg: &Config, place: Placement, issues: &mut Vec<String>) -> Result<ObjectPlan, FdmError> {
    // With a raft the OBJECT is an ordinary stack that starts with the normal layer height (the raft below it carries
    // `initial_layer_print_height`): the object lanes (slice, walls, surfaces, infill) see a config without the raft; the
    // support module and the G-code stage see the real one.
    let obj_owned;
    let ocfg: &Config = if cfg.raw("raft_layers").and_then(|v| v.trim().parse::<i64>().ok()).unwrap_or(0) > 0 {
        let mut c = Config::from_map(cfg.raw_map().clone());
        if let Some(lh) = cfg.raw("layer_height") { c.set("initial_layer_print_height", &lh.to_string()); }
        c.set("raft_layers", "0");
        obj_owned = c;
        &obj_owned
    } else { cfg };
    let slice_cfg = ocfg;
    let raft = cfg.raw("raft_layers").and_then(|v| v.trim().parse::<usize>().ok()).unwrap_or(0);
    if raft > 0 {
        issues.push("raft: surfaces now offset by the raft layers; sparse-infill fill-direction parity over a raft is still not offset (infill lane)".into());
    }
    let mut t0 = std::time::Instant::now();
    let sliced = slice::slice(&mesh, slice_cfg)?;
    stage(&mut t0, "slice");
    let layers = &sliced.layers;
    if layers.is_empty() { return Err(FdmError::Geometry("no layers".into())); }
    check_sliced(&sliced, &mesh, issues)?;
    if sliced.open_loops.len() > 0 {
        issues.push(format!("{} open loop(s) left after pre-repair (slice kept them out of the layer regions)", sliced.open_loops.len()));
    }

    // object bounding box (for 3D-phase infill patterns)
    let (mut lo, mut hi) = ([f64::MAX; 2], [f64::MIN; 2]);
    for v in &mesh.verts { for a in 0..2 { lo[a] = lo[a].min(v[a]); hi[a] = hi[a].max(v[a]); } }

    // 1. walls per layer (needs the layer below/above for overhangs and only_one_wall_top)
    // Layers are independent here; par_map writes each result to its own slot, so output is identical for any thread count.
    let threads = slice::default_threads();
    let fuzzy_cfg = fuzzy_config(cfg)?;
    // the wall generator refuses fuzzy_skin (this stage applies it to the finished loops), so it is given "none"
    let wall_owned;
    let wcfg: &Config = if fuzzy_cfg.is_some() { let mut c = Config::from_map(cfg.raw_map().clone()); c.set("fuzzy_skin", "none"); wall_owned = c; &wall_owned } else { cfg };
    let arachne_style = cfg.enum_("wall_generator").map(|g| g == "arachne").unwrap_or(false);
    // Elephant foot compensation (elfoot.rs, Orca slice_volumes): the first layers' OWN outline is shrunk for their
    // walls and surfaces; the neighbours and the G-code stage keep the uncompensated outline (Orca's lslices).
    let ef_s = num_of(cfg, "elefant_foot_compensation", 0.0);
    let ef_n = cfg.raw("elefant_foot_compensation_layers").and_then(|v| v.trim().parse::<usize>().ok()).unwrap_or(1);
    let ef_min_w = {
        let h0 = num_of(cfg, "initial_layer_print_height", 0.2);
        let w = cfg.f64("initial_layer_line_width").ok().filter(|w| *w > 0.0).or_else(|| cfg.f64("outer_wall_line_width").ok().filter(|w| *w > 0.0)).unwrap_or(0.42);
        w + (w - h0 * (1.0 - std::f64::consts::FRAC_PI_4))
    };
    let own_region: Vec<std::borrow::Cow<Polys>> = layers.iter().enumerate().map(|(i, l)| {
        let c = crate::elfoot::amount(ef_s, ef_n, i, raft);
        if c > 0.0 { std::borrow::Cow::Owned(crate::elfoot::compensate(&l.region, ef_min_w, c)) } else { std::borrow::Cow::Borrowed(&l.region) }
    }).collect();
    let mut wall_res: Vec<walls::WallResult> = slice::par_map(layers, threads, |i, l| {
        let lower = if i > 0 { Some(&layers[i - 1].region) } else { None };
        let upper = layers.get(i + 1).map(|u| &u.region);
        let wp = WallParams::from_config(wcfg, i + raft, l.h)?; // Layer::id() counts the raft layers
        walls::generate_walls(&own_region[i], lower, upper, &wp)
    }).into_iter().collect::<Result<_, FdmError>>()?;
    stage(&mut t0, "walls");
    // fuzzy skin: displaces the wall loops after they are generated (infill areas were derived from the clean walls)
    if let Some(fz) = &fuzzy_cfg {
        for (i, l) in layers.iter().enumerate() {
            let slice_z = l.z - l.h / 2.0;
            wall_res[i].paths = fuzzy::fuzzify_layer_walls(&wall_res[i].paths, &l.region, i as i64, slice_z, fz, arachne_style);
        }
    }

    // 2. classify surfaces across layers (needs sparse lines for internal-bridge direction/anchors)
    let geoms: Vec<LayerGeom> = layers.iter().zip(&wall_res).enumerate().map(|(i, (l, w))| LayerGeom {
        z: l.z, h: l.h, slice: own_region[i].clone().into_owned(),
        fill: w.infill_region.clone(), fill_no_overlap: w.infill_no_overlap.clone(),
    }).collect();
    let spiral = cfg.raw("spiral_mode").map_or(false, |v| matches!(v.trim(), "1" | "true"));
    let scfg_owned;
    let scfg_src: &Config = if spiral { let mut c = Config::from_map(ocfg.raw_map().clone()); c.set("spiral_mode", "0"); scfg_owned = c; &scfg_owned } else { ocfg };
    let mut scfg = SurfaceCfg::from_config(scfg_src)?;
    scfg.raft_layers = raft;   // surfaces offset first-layer widths / fill parity by the raft layers (Orca Layer::id counts them)
    let bottom_layers = cfg.raw("bottom_shell_layers").and_then(|v| v.trim().parse::<usize>().ok()).unwrap_or(0);
    let get = |k: &str| ocfg.raw(k).map(|s| s.to_string());
    let ctx_for = |i: usize| -> Result<InfillCtx, FdmError> {
        let mut c = InfillCtx::from_settings(&get, i, layers[i].z, layers[i].h).map_err(FdmError::Parse)?;
        c.object_bbox = Some(([lo[0], lo[1]], [hi[0], hi[1]]));
        // libslic3r phases patterns in object space, centred on the object: centre = origin = bbox centre
        let ctr = [(lo[0] + hi[0]) / 2.0, (lo[1] + hi[1]) / 2.0];
        c.center = ctr;
        c.origin = Some(ctr);
        Ok(c)
    };
    let sparse_for_anchor = SparseFn(|i: usize, region: &Polys| match ctx_for(i) {
        Ok(c) => infill::fill_sparse(region, &c).map(|p| to_points(&p)).unwrap_or_default(),
        Err(_) => Vec::new(),
    });
    let classified = surfaces::classify(&geoms, &scfg, Some(&sparse_for_anchor))?;
    stage(&mut t0, "classify");

    // ironing (Layer::make_ironing): needs the typed surfaces; None when ironing_type is "no ironing"
    let iron_cfg = ironing_config(cfg)?;
    let ctr = [(lo[0] + hi[0]) / 2.0, (lo[1] + hi[1]) / 2.0];
    let iron_angle = if cfg.f64("top_layer_direction").unwrap_or(-1.0) >= 0.0 { cfg.f64("top_layer_direction").unwrap_or(0.0) } else { cfg.f64("solid_infill_direction").unwrap_or(45.0) }.to_radians();
    let direction_fixed = cfg.f64("top_layer_direction").unwrap_or(-1.0) >= 0.0;
    let model_rotation = if cfg.bool_("align_infill_direction_to_model").unwrap_or(false) { place.rotate_z_deg.to_radians() } else { 0.0 };
    let sparse_density = cfg.raw("sparse_infill_density").and_then(|v| v.trim().trim_end_matches('%').parse::<f64>().ok()).unwrap_or(15.0);

    // 3. per layer: walls, solid surfaces, sparse infill, ironing
    let plans: Vec<LayerPlan> = slice::par_map(layers, threads, |i, l| -> Result<LayerPlan, FdmError> {
        let mut paths = wall_res[i].paths.clone();
        if spiral && i >= bottom_layers {
            // vase mode: only the outer wall above the bottom shell (no surfaces, infill or ironing)
            return Ok(LayerPlan { z: l.z, h: l.h, paths });
        }
        paths.extend(surfaces::fill_layer(i, &geoms, &classified, &scfg));
        if spiral && bottom_layers > 0 && i + 1 == bottom_layers {
            // Orca retypes the last bottom layer of a vase as a top surface (the wall spirals up from it)
            for q in paths.iter_mut() { if q.feature == Feature::InternalSolidInfill { q.feature = Feature::TopSurface; } }
        }
        let sparse = classified.sparse(i);
        if !sparse.is_empty() {
            let c = ctx_for(i)?;
            if c.density > 0.0 {
                match infill::fill_sparse(&sparse, &c) {
                    Ok(p) => paths.extend(p),
                    Err(e) => return Err(FdmError::Unsupported(format!("sparse infill, layer {i}: {e}"))),
                }
            }
        }
        if let Some(ic) = &iron_cfg {
            let tys = |t: &[SurfaceType]| -> Polys { geom::union_all(&[&classified.slices[i].iter().filter(|s| t.contains(&s.ty)).map(|s| s.poly.clone()).collect::<Polys>()]) };
            let has_non_solid = classified.fill[i].iter().any(|s| (s.ty == SurfaceType::Internal && sparse_density <= 95.0) || s.ty == SurfaceType::InternalBridge);
            let region = IroningRegion {
                top: tys(&[SurfaceType::Top]), bottom: tys(&[SurfaceType::Bottom]), all: l.region.clone(),
                internal_solid: classified.region(i, &[SurfaceType::InternalSolid]), has_non_solid_fill: has_non_solid,
            };
            let il = IroningLayer { layer_id: i, is_topmost: i + 1 == layers.len(), lslices: l.region.clone(), top_layer_base_angle: iron_angle,
                direction_fixed, ref_point: ctr, model_rotation };
            paths.extend(ironing::make_ironing(ic, &il, &[region]));
        }
        Ok(LayerPlan { z: l.z, h: l.h, paths })
    }).into_iter().collect::<Result<_, FdmError>>()?;
    stage(&mut t0, "fill");
    if plans.iter().any(|p| p.paths.iter().any(|q| matches!(q.feature, Feature::Skirt | Feature::Brim))) {
        issues.push("a lane emitted Skirt/Brim paths: the G-code stage then prints only those and generates no skirt/brim of its own".into());
    }

    // 3b. supports and raft: generated from the object layers, merged into the print by z
    let (plans, slices_per_plan) = merge_supports(cfg, slice_cfg, &mesh, layers, plans, ctr, issues)?;
    stage(&mut t0, "supports");

    Ok(ObjectPlan { mesh, plans, slices: slices_per_plan, open_loops: sliced.open_loops.len(), centre: ctr })
}

fn slice_inner(stl: &[u8], cfg: &Config, place: Placement) -> Result<PipelineOutput, FdmError> {
    let mut issues: Vec<String> = Vec::new();
    let mut mesh = prepare_mesh(stl, &mut issues)?;
    rotate_z(&mut mesh, place.rotate_z_deg);
    mesh.place_on_bed(place.center[0], place.center[1]);
    check_bed(&mesh, cfg, place)?;
    refuse_unwired(cfg)?;
    refuse_bad_values(cfg)?;
    let op = plan_object(mesh, cfg, place, &mut issues)?;
    let (mesh, plans, slices_per_plan, open_loops) = (op.mesh, op.plans, op.slices, op.open_loops);
    // 4. motion + G-code
    let settings = Settings::from_config(cfg);
    let mut opts = GcodeOptions::default();
    opts.slices = Some(slices_per_plan);
    // mesh in the SAME (rotated, placed) frame as the layers: the seam scorer ray-casts visibility against it
    // The layers ARE the rotated, placed mesh, so the seam scorer gets the rotated, placed triangles with rot_deg = 0 (an identity
    // frame). Measured on rotated parts (orcatest_A 270 deg, gk_edges 90, thin box 90, self-overlapping cubes 270): this frame
    // reproduces Orca's seam positions (position_match PASS); passing the UNROTATED mesh with rot_deg = the placement rotation
    // (rotation about the image of the rotation centre) gave 33-67% / 0% on the same models, so it is NOT equivalent.
    opts.seam_mesh = Some(gcode::SeamMesh {
        tris: (0..mesh.tris.len()).map(|i| mesh.tri(i)).collect(),
        rot_deg: 0.0, center: [0.0, 0.0] });
    let out = match gcode::generate(&plans, &settings, &opts) {
        Ok(o) => o,
        Err(FdmError::Geometry(m)) if m.contains("every LayerPlan is empty") => {
            return Err(FdmError::Geometry(format!("{m}; {}", describe_defects(&mesh.validate(), open_loops))));
        }
        Err(e) => return Err(e),
    };
    absorb_settings_reads(cfg, &settings);
    issues.extend(out.issues);
    Ok(PipelineOutput { gcode: out.gcode, layers: plans.len(), plans, issues, open_loops: open_loops })
}

